"""Writers for every target.

* URDF (neutral and Gazebo flavour) and mesh export
* MJCF: armature, actuators, mimic and loop equalities, contact excludes, keyframes (what URDF can't carry)
* SRDF with a self-collision matrix sampled in MuJoCo on the collision geometry (reasons follow MoveIt:
  Adjacent, Default, Always, Never; SAPIEN/ManiSkill only honour Default); it also feeds the MJCF excludes
* side files URDF can't express: Isaac Lab ArticulationCfg, ManiSkill agent class, Gazebo ros2_control
"""

from __future__ import annotations

